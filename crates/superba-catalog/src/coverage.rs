//! Coverage of the text layer: how many entries have official English text, a
//! maintainer's English note, a current or stale Chinese text.

use std::collections::BTreeMap;
use std::fmt::Write as _;

use crate::format::{Os, Stage, VersionCatalog};
use crate::overlay::{EntryId, Overlay, ZhState};

/// Counts for one group of entries.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct Counts {
    /// Entries.
    pub total: usize,
    /// Entries with official upstream English text.
    pub en_official: usize,
    /// Entries without official English text (flagged).
    pub en_missing: usize,
    /// Of those, entries with a maintainer's English note.
    pub en_note: usize,
    /// Chinese text written against the current English.
    pub zh_current: usize,
    /// Chinese text written against older English.
    pub zh_stale: usize,
    /// No Chinese text.
    pub zh_missing: usize,
}

impl Counts {
    fn add(&mut self, en_official: bool, en_note: bool, zh: ZhState) {
        self.total += 1;
        if en_official {
            self.en_official += 1;
        } else {
            self.en_missing += 1;
            if en_note {
                self.en_note += 1;
            }
        }
        match zh {
            ZhState::Current => self.zh_current += 1,
            ZhState::Stale => self.zh_stale += 1,
            ZhState::Missing => self.zh_missing += 1,
        }
    }

    fn merge(&mut self, o: &Counts) {
        self.total += o.total;
        self.en_official += o.en_official;
        self.en_missing += o.en_missing;
        self.en_note += o.en_note;
        self.zh_current += o.zh_current;
        self.zh_stale += o.zh_stale;
        self.zh_missing += o.zh_missing;
    }
}

/// Coverage report.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct Coverage {
    /// Catalog version stages were taken from.
    pub catalog_version: Option<String>,
    /// OS stages were evaluated for.
    pub os: Option<Os>,
    /// Per overlay file.
    pub by_file: BTreeMap<String, Counts>,
    /// Features per stage (in the catalog version).
    pub features_by_stage: BTreeMap<Stage, Counts>,
    /// Per entry kind (`feature`, `config`, `value`).
    pub by_kind: BTreeMap<&'static str, Counts>,
    /// All live entries.
    pub total: Counts,
    /// Retired entries kept for their written text.
    pub retired: usize,
    /// Ids without official English text, for the contributor queue.
    pub en_missing_ids: Vec<String>,
}

impl Coverage {
    /// Compute coverage of `overlay`; `latest` provides feature stages.
    pub fn compute(overlay: &Overlay, latest: Option<&VersionCatalog>, os: Os) -> Coverage {
        let mut cov = Coverage {
            catalog_version: latest.map(|c| c.codex_version.clone()),
            os: Some(os),
            ..Coverage::default()
        };
        for (id, file, e) in overlay.iter() {
            if e.retired.is_some() {
                cov.retired += 1;
                continue;
            }
            let official = e.has_official_en();
            let note = e.has_en_note();
            let zh = e.zh_state();
            cov.by_file
                .entry(file.to_owned())
                .or_default()
                .add(official, note, zh);
            cov.total.add(official, note, zh);
            let parsed = EntryId::parse(id).ok();
            let kind = match &parsed {
                Some(EntryId::Feature(_)) => "feature",
                Some(EntryId::Config(_)) => "config",
                Some(EntryId::Value { .. }) => "value",
                None => "unknown",
            };
            cov.by_kind.entry(kind).or_default().add(official, note, zh);
            if let (Some(EntryId::Feature(key)), Some(cat)) = (&parsed, latest) {
                let stage = cat.feature(key).map_or(Stage::Unknown, |f| f.stage_on(os));
                cov.features_by_stage
                    .entry(stage)
                    .or_default()
                    .add(official, note, zh);
            }
            if !official {
                cov.en_missing_ids.push(id.to_owned());
            }
        }
        cov
    }

    /// Markdown report (`catalog/COVERAGE.md`).
    pub fn to_markdown(&self) -> String {
        let mut s = String::new();
        s.push_str("# Catalog text coverage\n\n");
        s.push_str("Generated by `superba-catalog-gen coverage --write`; do not edit by hand.\n\n");
        if let Some(v) = &self.catalog_version {
            let _ = writeln!(
                s,
                "Feature stages from Codex {v} ({}).\n",
                self.os.map_or("linux", Os::as_str)
            );
        }
        s.push_str(
            "- **English (official)**: upstream text from the schema or the experimental \
             feature menu.\n- **English missing**: upstream has no text; such entries are \
             flagged and may get a maintainer's `en_note`.\n- **Chinese current / stale \
             / missing**: Chinese name and explanation, written per entry from the codex \
             source, against the current English, against older English, or not yet.\n\n",
        );
        let header = "| | Entries | English (official) | English missing | with en_note | Chinese current | Chinese stale | Chinese missing |\n|---|---:|---:|---:|---:|---:|---:|---:|\n";
        let row = |s: &mut String, name: &str, c: &Counts| {
            let _ = writeln!(
                s,
                "| {name} | {} | {} | {} | {} | {} | {} | {} |",
                c.total,
                c.en_official,
                c.en_missing,
                c.en_note,
                c.zh_current,
                c.zh_stale,
                c.zh_missing
            );
        };
        s.push_str("## Totals\n\n");
        s.push_str(header);
        for (k, c) in &self.by_kind {
            row(&mut s, k, c);
        }
        row(&mut s, "**all**", &self.total);
        let _ = writeln!(
            s,
            "\nRetired entries kept for their written text: {}.\n",
            self.retired
        );

        s.push_str("## Features by stage\n\n");
        s.push_str(header);
        let mut feats = Counts::default();
        for (stage, c) in &self.features_by_stage {
            row(&mut s, stage.cli_str(), c);
            feats.merge(c);
        }
        row(&mut s, "**all features**", &feats);

        s.push_str("\n## By overlay file\n\n");
        s.push_str(header);
        for (f, c) in &self.by_file {
            row(&mut s, &format!("`{f}`"), c);
        }
        s
    }
}
